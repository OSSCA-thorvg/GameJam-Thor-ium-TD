#pragma once
#include <optional>
#include <string>
#include <unordered_map>

namespace thorium::engine {
/** Half-open source frame interval; the end boundary never belongs to the next clip. */
struct FrameRange {
    float begin = 0;
    float end = 0;
};
/** Immutable adapter-provided metadata; independent of ThorVG and gameplay concepts. */
struct AnimationInfo {
    float frames = 0;
    float duration = 0;
    std::unordered_map<std::string, FrameRange> markers;
    float width = 0;
    float height = 0;
};
using AnimationAssets = std::unordered_map<std::string, AnimationInfo>;
/** Playback policy belongs to the player, rather than the renderer. */
enum class Playback { Loop, Once, Pose };
/** Repeated state requests preserve time unless a new action explicitly restarts playback. */
enum class Restart { IfChanged, Always };
/** Resolved immutable clip whose timing is derived from source metadata. */
struct AnimationClip {
    std::string asset;
    FrameRange frames;
    float duration = 0;
    Playback playback = Playback::Loop;
    /** Validate finite source bounds and a positive duration before committing playback. */
    bool valid() const;
    /** Compare playback identity without depending on an object's address. */
    bool operator==(const AnimationClip &other) const;
};
/** One absolute source frame to draw; carries no mutable playback clock. */
struct AnimationSample {
    std::string asset;
    float frame = 0;
    FrameRange frames{};
};
/** Resolve a named source segment, deriving its duration from source FPS. */
std::optional<AnimationClip> animationClip(const std::string &asset, const AnimationInfo &info,
                                           const std::string &marker, Playback playback);
/** Sample an explicit UI clock without giving a renderer ownership of time or loop policy. */
AnimationSample loopingSample(const AnimationClip &clip, float seconds);

/** Own one portable playback clock; completion is an edge consumed at most once. */
class AnimationPlayer {
  public:
    /** Start a valid clip, preserving an identical request unless restart is explicit. */
    bool play(const AnimationClip &clip, Restart restart = Restart::IfChanged);
    /** Clear playback without publishing a spurious completion. */
    void stop();
    /** Freeze local time; global pause may instead withhold advance entirely. */
    void pause();
    /** Resume the current clip at its existing local time. */
    void resume();
    /** Set a finite nonnegative local rate without changing clip position. */
    bool setSpeed(float speed);
    /** Advance seconds once, wrapping loops or holding a completed one-shot's last frame. */
    void advance(float seconds);
    /** Read the current source frame, or no sample when stopped. */
    std::optional<AnimationSample> sample() const;
    /** Set a stable normalized phase used only when sampling loop clips. */
    bool setLoopPhase(float phase);
    /** Read the stable normalized phase without changing the local clock. */
    float loopPhase() const;
    /** Read whether a one-shot reached its end; repeated play requests do not reset it. */
    bool finished() const;
    /** Consume the one completion edge generated by a one-shot. */
    bool takeCompletion();
    /** Read clip-local seconds for diagnostics and deterministic tests. */
    float elapsed() const;

  private:
    std::optional<AnimationClip> clip_;
    double elapsed_ = 0;
    float speed_ = 1;
    float loopPhase_ = 0;
    bool paused_ = false;
    bool finished_ = false;
    bool completion_ = false;
};
} // namespace thorium::engine
